# Määritellään muuttujat

kokonaisluku1 = int(input('Anna ensimmäinen kokonaisluku: '))
kokonaisluku2 = int(input('Anna toinen kokonaisluku: '))
kokonaisluku3 = int(input('Anna kolmas kokonaisluku: '))

# Tulostetaan laskutoimitukset

print('Kokonaislukujen summa on: ' + str(kokonaisluku1 + kokonaisluku2 + kokonaisluku3))
print('Kokonaislukujen tulo on: ' + str(kokonaisluku1 * kokonaisluku2 * kokonaisluku3))
print('Kokonaislukujen keskiarvo on: ' + str((kokonaisluku1 + kokonaisluku2 + kokonaisluku3) / 3))